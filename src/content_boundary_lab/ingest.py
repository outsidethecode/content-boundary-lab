def build_initiate_endpoint(
    settings: TrustedSettings, clock: Clock, database_path: Path, max_upload_bytes: int
) -> Callable[[str, Request, request_flow.RequestBody], Response]:
    """The handler for POST .../deliveries. The body is read by read_body, before the handler, in the event loop."""

    # A plain def, so the framework runs it in a worker thread: the SQLite connection is opened and used there.
    def initiate_delivery(
        production_id: str, request: Request, body: request_flow.RequestBody = Depends(request_flow.read_body)
    ) -> Response:
        return request_flow.handle(
            settings,
            clock,
            database_path,
            production_id=production_id,
            authorization=request_flow.authorization_value(request),
            action=authz.Action.INITIATE_DELIVERY,
            operation=functools.partial(_initiate, limit=max_upload_bytes),
            body=body,
        )

    return initiate_delivery


def build_upload_endpoint(
    settings: TrustedSettings, clock: Clock, database_path: Path, quarantine_root: Path, max_upload_bytes: int
) -> Callable[[str, str, Request], object]:
    """The handler for PUT .../deliveries/{delivery_id}/content. It streams the body: it declares no body parameter."""

    # An async def, because the body is awaited chunk by chunk; every database and file step runs in a worker thread.
    async def upload_content(production_id: str, delivery_id: str, request: Request) -> Response:
        return await _upload(
            request, production_id, delivery_id, settings, clock, database_path, quarantine_root, max_upload_bytes
        )

    return upload_content
