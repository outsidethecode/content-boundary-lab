MAX_NAME_LENGTH = 200  # the schema's bound on a display name
_ID = re.compile(r"[0-9a-f]{32}")
_SHA256 = re.compile(r"[0-9a-f]{64}")
_MEDIA_TYPE = re.compile(r"[A-Za-z0-9][A-Za-z0-9!#$&^_.+-]{0,126}/[A-Za-z0-9][A-Za-z0-9!#$&^_.+-]{0,126}")
_MEMBERS = frozenset({"display_name", "declared_size", "declared_sha256", "declared_media_type"})
_FORBIDDEN_CATEGORIES = frozenset({"Cc", "Cs", "Cf", "Zl", "Zp"})  # controls, surrogates, format (bidi), separators
_FORBIDDEN_NAME_CHARACTERS = frozenset("/\\")
_BIGGER_THAN_ANY_LIMIT = 10**18
_INITIATED = store.DeliveryState.INITIATED.value

# The only SQL that names the deliveries table in this module (tests/guards/test_delivery_scope.py checks that).
_LOOKUP = (
    "SELECT d.id, d.production_id, d.owner_subject_id, d.storage_key, d.state, d.declared_size, d.declared_sha256, "
    "d.received_size, d.received_sha256 FROM deliveries AS d "
    "JOIN engagements AS e ON e.production_id = d.production_id AND e.subject_id = d.owner_subject_id "
    "JOIN subjects AS s ON s.id = d.owner_subject_id "
    "WHERE d.id = ? AND d.production_id = ? AND s.issuer = ? AND s.subject = ? "
    "AND e.revoked_at IS NULL AND e.ends_at > ?"
)
_RECEIVE = (
    "UPDATE deliveries SET state = 'UPLOADED', received_size = ?, received_sha256 = ?, uploaded_at = ? "
    "WHERE id = ? AND production_id = ? AND owner_subject_id = ? AND state = 'INITIATED'"
)
_STATE_BY_KEY = "SELECT state FROM deliveries WHERE storage_key = ?"
_COMMITTED = "SELECT id, storage_key FROM deliveries WHERE state != 'INITIATED'"


@dataclass(frozen=True)
class Delivery:
    """A delivery the caller owns and may reach now. The storage key never leaves the server.

    declared_size and declared_sha256 are the vendor's claims, for comparison with what the server measures at seal time
    and for nothing else; received_size and received_sha256 are the intake receipt (None before the upload).
    """

    id: str
    production_id: str
    owner_subject_id: int
    storage_key: str
    state: str
    declared_size: int
    declared_sha256: str
    received_size: int | None
    received_sha256: str | None


def get_delivery_in_scope(
    conn: sqlite3.Connection, caller: VerifiedIdentity, production_id: str, delivery_id: str, now_micros: int
) -> Delivery | None:
    """The delivery, if `caller` owns it in the production the request named and is engaged there at this instant.

    One parameterised SELECT binds the delivery, its real production, the requested production, the owner's verified
    (issuer, subject) and the owner's current, unrevoked engagement. A delivery that is missing, in another production,
    owned by someone else or not reachable now gives the same answer (None). The role is the request flow's decision.
    The caller owns the transaction and supplies the one instant of the request; this reads no clock and writes nothing.
    """
    if not isinstance(caller, VerifiedIdentity):
        raise TypeError("caller must be a VerifiedIdentity")
    for name, value in (("production_id", production_id), ("delivery_id", delivery_id)):
        if type(value) is not str:
            raise TypeError(f"{name} must be a str, got {type(value).__name__}")
        if not _ID.fullmatch(value):
            raise ValueError(f"{name} must be 32 lowercase hexadecimal characters")  # the value is never echoed
    if type(now_micros) is not int:
        raise TypeError("now_micros must be an int (a bool is not accepted)")
    if not conn.in_transaction:
        raise StoreError("a delivery lookup must run inside the caller's transaction")
    row = conn.execute(_LOOKUP, (delivery_id, production_id, caller.issuer, caller.subject, now_micros)).fetchone()
    return None if row is None else Delivery(*row)


# --- declaring a delivery -----------------------------------------------------------------------------------------------


class _Invalid(Exception):
    """A request body that failed validation. It carries only the name of a fixed field, never any of the input."""

    def __init__(self, field: str) -> None:
        super().__init__(field)
        self.field = field


def _no_repeats(pairs: list[tuple[str, object]]) -> dict:
    names = [name for name, _ in pairs]
    if len(names) != len(set(names)):
        raise ValueError("repeated member name")
    return dict(pairs)


def _reject_constant(name: str) -> None:
    raise ValueError(name)


def _display_name(value: object) -> str:
    """A plain name: 1 to 200 characters, none of them a separator, control or format character, and not `.` or `..`."""
    if (
        type(value) is not str
        or not 1 <= len(value) <= MAX_NAME_LENGTH
        or value in {".", ".."}
        or any(char in _FORBIDDEN_NAME_CHARACTERS or unicodedata.category(char) in _FORBIDDEN_CATEGORIES for char in value)
    ):
        raise _Invalid("display_name")
    return value


def _parse(data: bytes, limit: int) -> tuple[str, int, str, str]:
    """(display_name, declared_size, declared_sha256, declared_media_type) from a body that is exactly those four."""
    try:
        document = json.loads(data.decode("utf-8"), object_pairs_hook=_no_repeats, parse_constant=_reject_constant)
    except (ValueError, RecursionError):  # not UTF-8, not JSON, a repeated member, NaN or Infinity, or too deeply nested
        raise _Invalid("body") from None
    if type(document) is not dict or document.keys() != _MEMBERS:
        raise _Invalid("body")
    name = _display_name(document["display_name"])
    size = document["declared_size"]
    if type(size) is not int or not 0 <= size <= limit:  # a bool is not a size; nothing over the limit can be uploaded
        raise _Invalid("declared_size")
    sha256 = document["declared_sha256"]
    if type(sha256) is not str or not _SHA256.fullmatch(sha256):
        raise _Invalid("declared_sha256")
    media_type = document["declared_media_type"]
    if type(media_type) is not str or not _MEDIA_TYPE.fullmatch(media_type):
        raise _Invalid("declared_media_type")
    return name, size, sha256, media_type


def _reject(
    ctx: request_flow.Context,
    status: int,
    detail: str,
    reason: audit.AuditReason,
    *,
    field: str | None = None,
    delivery_id: str | None = None,
) -> request_flow.Decision:
    """Record an authorised request that was refused, and answer it. Nothing of the request is recorded or echoed."""
    audit.record_event(
        ctx.conn,
        ctx.clock,
        audit.AuditAction.DELIVERY_REQUEST_REJECTED,
        audit.Outcome.DENIED,
        actor=ctx.caller.as_actor(),
        production_id=ctx.production_id,
        object_type=None if delivery_id is None else audit.ObjectType.DELIVERY,
        object_id=delivery_id,
        reason=reason,
    )
    return request_flow.Decision(status, {"detail": detail} if field is None else {"detail": detail, "field": field})


def _initiate(ctx: request_flow.Context, limit: int) -> request_flow.Decision:
    """Store the declaration as a delivery in INITIATED, owned by the caller in the URL's production."""
    if ctx.body is None:
        raise RuntimeError("the initiate operation needs the request body")
    if ctx.body.oversized:
        return _reject(ctx, 413, "Payload too large", audit.AuditReason.PAYLOAD_TOO_LARGE)
    try:
        name, size, sha256, media_type = _parse(ctx.body.data, limit)
    except _Invalid as invalid:
        return _reject(ctx, 400, "Invalid request", audit.AuditReason.INVALID_REQUEST, field=invalid.field)
    owner = ctx.conn.execute(
        "SELECT id FROM subjects WHERE issuer = ? AND subject = ?", (ctx.caller.issuer, ctx.caller.subject)
    ).fetchone()
    if owner is None:  # the flow authorised this caller from a join on subjects in this same transaction
        raise RuntimeError("an authorised caller has no subject row")
    created = store.add_delivery(ctx.conn, ctx.clock, ctx.production_id, owner[0], name, size, sha256, media_type)
    audit.record_event(
        ctx.conn,
        ctx.clock,
        audit.AuditAction.DELIVERY_INITIATED,
        audit.Outcome.ALLOWED,
        actor=ctx.caller.as_actor(),
        production_id=ctx.production_id,
        object_type=audit.ObjectType.DELIVERY,
        object_id=created.id,
    )
    return request_flow.Decision(201, {"delivery_id": created.id, "state": _INITIATED})


# --- admitting an upload (the first transaction) -----------------------------------------------------------------------


@dataclass(frozen=True)
class _Admitted:
    """What the first transaction established, handed to the second: the decision it returned, who, and which delivery."""

    decision: request_flow.Decision
    caller: VerifiedIdentity
    grant: authz.AuthorizedEngagement
    delivery: Delivery


def _record(ctx: request_flow.Context, action: audit.AuditAction, outcome: audit.Outcome, delivery_id: str, reason=None):
    audit.record_event(
        ctx.conn,
        ctx.clock,
        action,
        outcome,
        actor=ctx.caller.as_actor(),
        production_id=ctx.production_id,
        object_type=audit.ObjectType.DELIVERY,
        object_id=delivery_id,
        reason=reason,
    )


def _admit(
    ctx: request_flow.Context, delivery_id: str, content_length: int | None, limit: int, admitted: list[_Admitted]
) -> request_flow.Decision:
    """Decide whether the server will read this delivery's bytes. Reads nothing from the client."""
    if not _ID.fullmatch(delivery_id):  # the text is never looked up and never recorded as an object
        return request_flow.not_found(ctx, audit.AuditReason.INVALID_IDENTIFIER)
    delivery = get_delivery_in_scope(ctx.conn, ctx.caller, ctx.production_id, delivery_id, ctx.now_micros)
    if delivery is None:  # missing, in another production, someone else's: one and the same answer
        return request_flow.not_found(
            ctx,
            audit.AuditReason.NOT_FOUND_OR_FORBIDDEN,
            object_type=audit.ObjectType.DELIVERY,
            object_id=delivery_id,
        )
    if delivery.state != _INITIATED:
        return _reject(
            ctx, 409, "Delivery is not awaiting content", audit.AuditReason.STATE_CONFLICT, delivery_id=delivery.id
        )
    if content_length is not None and content_length > limit:  # a cheap early refusal; the count of real bytes decides
        return _reject(ctx, 413, "Payload too large", audit.AuditReason.PAYLOAD_TOO_LARGE, delivery_id=delivery.id)
    _record(ctx, audit.AuditAction.DELIVERY_UPLOAD_STARTED, audit.Outcome.ALLOWED, delivery.id)
    decision = request_flow.Decision(202, {"detail": "Accepted"})
    admitted.append(_Admitted(decision, ctx.caller, ctx.grant, delivery))
    return decision


def _content_length(request: Request) -> int | None:
    """The one Content-Length the client claims, if it is a plain number. It is a hint; real bytes are what is counted."""
    values = request.headers.getlist("content-length")
    if len(values) != 1 or not values[0].isascii() or not values[0].isdigit():
        return None
    return int(values[0]) if len(values[0]) <= 18 else _BIGGER_THAN_ANY_LIMIT


# --- receiving the bytes and completing (the second transaction) --------------------------------------------------------


def _finish_upload(
    ctx: request_flow.Context, delivery: Delivery, received: quarantine.Received, quarantine_root: Path
) -> request_flow.Decision:
    """Move INITIATED to UPLOADED with the measured receipt, put the file in place, and record it. All or nothing."""
    cursor = ctx.conn.execute(
        _RECEIVE,
        (received.size, received.sha256, ctx.now_micros, delivery.id, delivery.production_id, delivery.owner_subject_id),
    )
    if cursor.rowcount != 1:  # another upload to this delivery completed first
        _record(
            ctx,
            audit.AuditAction.DELIVERY_UPLOAD_FAILED,
            audit.Outcome.DENIED,
            delivery.id,
            audit.AuditReason.STATE_CONFLICT,
        )
        return request_flow.Decision(409, {"detail": "Delivery is not awaiting content"})
    # After the compare-and-set and before the commit: a failure from here on rolls the state back. publish() never
    # replaces, so a file already at the key makes it raise (nothing is changed, the row stays INITIATED, no event says
    # UPLOADED); a file it did place is taken back by the endpoint (_take_back_what_this_request_placed) and only that
    # one. This is not an atomic pair, and is not presented as one.
    quarantine.publish(quarantine_root, received.name, delivery.storage_key)
    _record(ctx, audit.AuditAction.DELIVERY_UPLOADED, audit.Outcome.ALLOWED, delivery.id)
    return request_flow.Decision(
        201,
        {
            "delivery_id": delivery.id,
            "state": store.DeliveryState.UPLOADED.value,
            "received_size": received.size,
            "received_sha256": received.sha256,
        },
    )


def _record_failure(ctx: request_flow.Context, delivery: Delivery, reason: audit.AuditReason) -> request_flow.Decision:
    """Record that a started upload ended without UPLOADED because of the limit or the client, and answer."""
    too_large = reason is audit.AuditReason.PAYLOAD_TOO_LARGE
    _record(
        ctx,
        audit.AuditAction.DELIVERY_UPLOAD_FAILED,
        audit.Outcome.DENIED if too_large else audit.Outcome.RECORDED,
        delivery.id,
        reason,
    )
    if too_large:
        return request_flow.Decision(413, {"detail": "Payload too large"})
    return request_flow.Decision(400, {"detail": "Upload interrupted"})  # the client is gone; this is for the logs' sake


def _take_back_what_this_request_placed(
    database_path: Path, quarantine_root: Path, delivery: Delivery, received: quarantine.Received
) -> bool:
    """After a completion that failed, remove the file this request placed at the storage key, and nothing else.

    Two conditions, both decided with the writer lock held. The delivery must still be INITIATED: otherwise the
    transaction did commit (an error came after it) and the file is the delivery's bytes. And the entry at the key must
    be the very file this request wrote, by device and inode (Received): a file that was already there when the placement
    was refused, one that replaced ours since, or nothing, is left exactly as it is. Re-reading the state with the lock
    held also stops the removal from touching the file of an upload that is committing at the same moment: while that
    upload holds the lock this waits, and afterwards it sees UPLOADED. True if a file was removed.
    """
    conn = store.connect(database_path)
    try:
        with store.transaction(conn):
            row = conn.execute(_STATE_BY_KEY, (delivery.storage_key,)).fetchone()
            if row is None or row[0] != _INITIATED:
                return False
            return quarantine.remove_if_same_file(quarantine_root, delivery.storage_key, received.device, received.inode)
    finally:
        conn.close()


def _clean_up_after_failure(
    database_path: Path, quarantine_root: Path, delivery: Delivery, received: quarantine.Received
) -> None:
    try:
        _take_back_what_this_request_placed(database_path, quarantine_root, delivery, received)
    except Exception:  # the answer to the client stands; the leftover is ours but unprovable now: reconcile() reports it
        logger.error("could not take back a file left by a failed upload; reconcile() will report it", exc_info=True)


def _discard(incoming: quarantine.IncomingFile) -> None:
    try:
        incoming.discard()
    except OSError:
        logger.error("could not remove a staged upload; reconcile() will", exc_info=True)


async def _receive(
    request: Request,
    admitted: _Admitted,
    clock: Clock,
    database_path: Path,
    quarantine_root: Path,
    limit: int,
) -> Response:
    """Read the body into a staged file, then finish or abandon the upload. Every path leaves nothing staged."""
    delivery = admitted.delivery
    incoming: quarantine.IncomingFile | None = None
    try:
        incoming = await run_in_threadpool(quarantine.IncomingFile.create, quarantine_root, limit)
        failure_reason: audit.AuditReason | None = None
        try:
            async for chunk in request.stream():  # one chunk at a time: the body is never gathered in memory
                if chunk:  # the framework ends the stream with an empty chunk; there is nothing to write for it
                    await run_in_threadpool(incoming.write, chunk)
        except quarantine.UploadTooLarge:
            failure_reason = audit.AuditReason.PAYLOAD_TOO_LARGE
        except ClientDisconnect:
            failure_reason = audit.AuditReason.UPLOAD_INTERRUPTED
        if failure_reason is not None:
            await run_in_threadpool(_discard, incoming)  # the bytes are gone before the record says the upload failed
            decision = await run_in_threadpool(
                request_flow.proceed,
                clock,
                database_path,
                caller=admitted.caller,
                grant=admitted.grant,
                production_id=delivery.production_id,
                operation=functools.partial(_record_failure, delivery=delivery, reason=failure_reason),
            )
            return request_flow.respond(decision)
        received = await run_in_threadpool(incoming.finish)
        decision = await run_in_threadpool(
            request_flow.proceed,
            clock,
            database_path,
            caller=admitted.caller,
            grant=admitted.grant,
            production_id=delivery.production_id,
            operation=functools.partial(
                _finish_upload, delivery=delivery, received=received, quarantine_root=quarantine_root
            ),
        )
        if decision.status >= 500:  # rolled back: a file may already have been placed, and only that one is taken back
            await run_in_threadpool(_clean_up_after_failure, database_path, quarantine_root, delivery, received)
        return request_flow.respond(decision)
    except Exception as error:  # a full disk, a failed write: the client learns nothing; the start event stands
        decision = request_flow.failure(error)
        return request_flow.respond(decision)
    finally:
        if incoming is not None:
            _discard(incoming)  # also when the request is cancelled; a no-op once the file has been put in place


async def _upload(
    request: Request,
    production_id: str,
    delivery_id: str,
    settings: TrustedSettings,
    clock: Clock,
    database_path: Path,
    quarantine_root: Path,
    limit: int,
) -> Response:
    admitted: list[_Admitted] = []
    decision = await run_in_threadpool(
        request_flow.decide,
        settings,
        clock,
        database_path,
        production_id=production_id,
        authorization=request_flow.authorization_value(request),
        action=authz.Action.UPLOAD_DELIVERY,
        operation=functools.partial(
            _admit, delivery_id=delivery_id, content_length=_content_length(request), limit=limit, admitted=admitted
        ),
    )
    # Only the very decision the committed operation returned admits the upload: a failure after the operation (the audit
    # count, the commit) answers with a different Decision, and then not one byte is read.
    if not admitted or admitted[0].decision is not decision:
        return request_flow.respond(decision)
    return await _receive(request, admitted[0], clock, database_path, quarantine_root, limit)


# --- reconciliation -----------------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class ReconcileReport:
    """What reconcile() did and what it found. Only the first tuple is a thing it changed.

    removed_incoming: staged files removed (older than the minimum age). ambiguous: storage keys of deliveries that are
    still INITIATED yet have a regular file: it may be what a crashed upload left or something someone placed, and nothing
    recorded can say which, so it is left for a person. unreferenced: server-named files that no delivery claims (left
    alone). foreign: entries that are not the server's (left alone). missing: ids of deliveries past INITIATED whose file
    is not a regular file in quarantine (not repaired: there is no state to move them to and no bytes to invent).
    """

    removed_incoming: tuple[str, ...]
    ambiguous: tuple[str, ...]
    unreferenced: tuple[str, ...]
    foreign: tuple[str, ...]
    missing: tuple[str, ...]


def _classify_final(database_path: Path, storage_key: str) -> str:
    """"claimed" (its delivery is UPLOADED or later), "ambiguous" (still INITIATED) or "unreferenced" (no delivery).

    The state is read with the writer lock held, so a completion that is committing at this moment has finished and is
    seen as UPLOADED. Nothing is removed: a file at the key of an INITIATED delivery cannot be proved to be anyone's.
    """
    conn = store.connect(database_path)
    try:
        with store.transaction(conn):
            row = conn.execute(_STATE_BY_KEY, (storage_key,)).fetchone()
            if row is None:
                return "unreferenced"
            return "ambiguous" if row[0] == _INITIATED else "claimed"
    finally:
        conn.close()


def reconcile(clock: Clock, database_path: Path, quarantine_root: Path, *, min_age: timedelta) -> ReconcileReport:
    """Report what a crash or a failed cleanup left in quarantine, and remove old staged files. Repeating it changes nothing more.

    A MANUAL, MAINTENANCE-WINDOW operation. No uploads may be active while it runs: an upload is not recognisable from
    outside, `min_age` is only an age threshold on the staged file's last write and not proof that its upload is
    inactive, and running this during an active upload can interrupt that upload (its staged file is removed from under
    it and it fails with a generic 500, the delivery still awaiting content). It must not be scheduled or called
    automatically under the current contract; M1M must establish an active-upload exclusion mechanism before any
    automated reconciliation is allowed. tests/test_quarantine_reconcile.py shows the interaction as it is observed.

    It removes only staged files at least `min_age` old (the server's own scratch space). It deletes no file at a storage
    key: one whose delivery is UPLOADED or later is the delivery's bytes; one whose delivery is INITIATED is reported as
    ambiguous for manual handling; one that no delivery claims, and anything that is not the server's, is reported and left
    alone, because a mistaken root must not cost anybody else's files. A delivery past INITIATED whose file is not a
    regular file is reported as missing, never repaired.
    """
    if not isinstance(min_age, timedelta):
        raise TypeError("min_age must be a timedelta")
    if min_age < timedelta(0):
        raise ValueError("min_age must not be negative")
    listing = quarantine.scan(quarantine_root)
    now = to_micros(clock.now())
    limit = min_age // timedelta(microseconds=1)
    removed_incoming = tuple(
        name
        for name, modified in listing.incoming
        if now - modified >= limit and quarantine.remove_staged(quarantine_root, name)
    )
    outcomes = {key: _classify_final(database_path, key) for key in listing.finals}
    conn = store.connect(database_path)
    try:
        committed = conn.execute(_COMMITTED).fetchall()
    finally:
        conn.close()
    missing = tuple(sorted(row[0] for row in committed if not quarantine.is_regular_file(quarantine_root, row[1])))
    return ReconcileReport(
        removed_incoming,
        tuple(key for key, outcome in outcomes.items() if outcome == "ambiguous"),
        tuple(key for key, outcome in outcomes.items() if outcome == "unreferenced"),
        listing.foreign,
        missing,
    )


