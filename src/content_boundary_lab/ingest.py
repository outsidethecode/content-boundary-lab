"""Initiation and ingest (M0 §2 steps 3 and 4): a vendor declares a delivery, then streams its bytes into quarantine.

    POST /productions/{production_id}/deliveries                       declare      -> 201 {delivery_id, state: INITIATED}
    PUT  /productions/{production_id}/deliveries/{delivery_id}/content upload       -> 201 {delivery_id, state: UPLOADED,
                                                                                         received_size, received_sha256}

Only a vendor with an active engagement in the production of the URL may do either (authz actions `initiate_delivery`
and `upload_delivery`); a coordinator may not. The production always comes from the URL. A delivery belongs to the
vendor that declared it, in that production, and only that subject can upload to it: another vendor, even one engaged
in the same production, gets the same generic 404 as for an id that does not exist.

The lifecycle belongs to the deliveries table (store.DeliveryState), not to the assets table. This module moves a
delivery from nothing to INITIATED and from INITIATED to UPLOADED, and no further: sealing, hashing for identity, the
declared-against-actual checks, the scanner, acceptance and promotion are later milestones (M1I to M1K).

Declaration. A JSON object with exactly `display_name`, `declared_size`, `declared_sha256` and `declared_media_type`.
They are the client's claims, stored as metadata for the later consistency checks and for display. None of them is a
path, a key, an identity or a limit: the display name must be a plain name (no path separator, no control or format
character, not `.` or `..`) and is never used to build a path; the storage key is generated by the server (store.
add_delivery); the declared hash does not identify content. The body is read before the transaction (request_flow.
read_body, 4 KiB) and judged after authentication and authorisation. Nothing is written to the filesystem.

Upload. The bytes are streamed to quarantine between two short transactions, so that no database lock is held while a
slow client sends them:

    1. request_flow.decide(): BEGIN IMMEDIATE, authenticate, authorise, look the delivery up in scope (its production,
       its owner, a current engagement), require state INITIATED, refuse an honest Content-Length over the limit, record
       `delivery.upload_started`, COMMIT. Nothing has been read from the client yet.
    2. The body is read chunk by chunk (never gathered), counted on the bytes that actually arrive, hashed, and written
       to a staged file under quarantine/.incoming with a server-made name (quarantine.IncomingFile). At the limit the
       reading stops and the staged bytes are removed; a client that goes away has them removed too.
    3. request_flow.proceed(): BEGIN IMMEDIATE, compare-and-set INITIATED -> UPLOADED with the measured size and digest,
       place the staged file at the delivery's storage key (quarantine.publish: a no-clobber hard link, never a
       replacement), record `delivery.uploaded`, COMMIT. It does not authenticate again (M0 §5.7: authorisation is
       checked when a request starts, and a started transfer may finish).

A SQLite transaction and a file placement are NOT one atomic step, and nothing here claims they are. The order is chosen
so that the failures are repairable: the placement comes after the compare-and-set and before the commit, so a crash or
a failed commit can leave a file that no committed row claims (never served, never read), but never a committed UPLOADED
row whose file was not placed.

Whose file is at a storage key. The placement refuses to replace anything, so a file that was already there makes the
upload fail closed: a generic 500, the delivery still INITIATED, no `delivery.uploaded`, this request's staged file
removed, and the existing entry (a file, a symlink even if dangling, a directory) exactly as it was. After a completion
that fails once the file has been placed, the request takes back that file and only that file: under the writer lock, if
the delivery is still INITIATED and the entry at the key is the very file this request wrote (same device and inode),
which a file that was already there, or one that replaced ours since, can never be. If the clean-up itself cannot run,
the leftover is this request's but nothing can prove it any longer, so it stays and reconcile() reports it as ambiguous.
No automatic step deletes a file at a storage key on the strength of the database's state alone; a person looks at an
ambiguous one and removes it, after which the delivery can be uploaded again.

If two uploads to one delivery are in flight, the compare-and-set lets one win and the other is refused with 409 and its
staged bytes removed; the loser never places a file. reconcile() is a manual maintenance-window operation (see it).
Nothing here is durable across a power failure.

Audit, one event for each committed decision (the request flow checks the count of each transaction):
`delivery.initiated`, `delivery.upload_started`, `delivery.uploaded` (all allowed); `delivery.request_rejected` (denied)
for an authorised request refused before any byte was kept (invalid, too large, or the delivery not awaiting content);
`delivery.upload_failed` for a started upload that ended another way: denied/payload_too_large, denied/state_conflict (it
lost the race), recorded/upload_interrupted (the client went away). `delivery.upload_started` records the committed
admission to begin receiving an upload; it does not say that any byte arrived or that the upload completed.
`delivery.uploaded` is written in the same transaction as the move to UPLOADED and the placement, so it exists only if
that transition committed; no event claims a successful upload when the placement fails. A server fault (a full disk, a
failed placement, a failed commit) and a cancelled request record no completion event: the start event stands, the
fault is logged, and the client gets the generic error. No filename, size, digest or path is recorded.
"""

